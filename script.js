const $ = (id) => document.getElementById(id);

let currentLanguage = "ar";
let supabaseClient = null;
let currentUser = null;
let editingMemoryId = null;
let memories = [];

const config = window.RAHAF_CONFIG || {};

const configured =
  config.supabaseUrl &&
  config.supabaseAnonKey &&
  !config.supabaseUrl.includes("YOUR_") &&
  !config.supabaseAnonKey.includes("YOUR_");

if (configured && window.supabase) {
  supabaseClient = window.supabase.createClient(
    config.supabaseUrl,
    config.supabaseAnonKey,
    {
      auth: {
        persistSession: false,
        autoRefreshToken: false,
        detectSessionInUrl: false,
      },
    },
  );
}

function t(key) {
  return translations[currentLanguage][key] || key;
}

// Language.
function setLanguage(language) {
  currentLanguage = language;

  const ar = language === "ar";

  document.documentElement.lang = language;
  document.documentElement.dir = ar ? "rtl" : "ltr";
  document.body.dir = ar ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;

    if (translations[language][key]) {
      el.innerHTML = translations[language][key];
    }
  });

  $("languageToggle").textContent = ar ? "English" : "العربية";

  localStorage.setItem("rahaf-site-language", language);

  if (currentUser) {
    $("accessLabel").textContent = t("rahafLabel");
  } else if (!$("mainContent").hidden) {
    $("accessLabel").textContent = t("guestLabel");
  }

  if (currentUser) renderMemories();
}

// Screens.
function showScreen(screen) {
  $("languageScreen").hidden = screen !== "languageScreen";
  $("loginScreen").hidden = screen !== "loginScreen";

  const inside = screen === "site";

  $("siteHeader").hidden = !inside;
  $("mainContent").hidden = !inside;
  $("siteFooter").hidden = !inside;
}
function enterPublicSite(isOwner) {
  $("memoryNav").hidden = !isOwner;
  $("memories").hidden = !isOwner;

  $("accessLabel").textContent = isOwner ? t("rahafLabel") : t("guestLabel");

  $("logoutButton").hidden = false;

  showScreen("site");

  window.scrollTo({ top: 0, behavior: "instant" });

  observeReveals();

  if (!planetarium3) {
    requestAnimationFrame(() => {
      initializeSkyMap();
    });
  }

  if (isOwner) {
    loadMemories();
  }
}

